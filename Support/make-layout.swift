// Turns Support/layout.json into Sources/machen/Layout.generated.swift (run by build.sh).
// Usage: swift Support/make-layout.swift <layout.json> <output.swift>
//
// Objects become nested enums and numbers become `static let` CGFloat constants, so a typo or a
// missing value fails the build instead of silently falling back. Keys starting with _ are comments.
import Foundation

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data("layout.json: \(message)\n".utf8))
    exit(1)
}

let args = CommandLine.arguments
guard args.count == 3 else { fail("usage: make-layout.swift <layout.json> <output.swift>") }
let (input, output) = (args[1], args[2])

let root: [String: Any]
do {
    let data = try Data(contentsOf: URL(fileURLWithPath: input))
    guard let object = try JSONSerialization.jsonObject(with: data) as? [String: Any] else { fail("expected an object at the top") }
    root = object
} catch {
    // JSONSerialization keeps the useful part ("… around line 12, column 5") in the debug description
    let detail = (error as NSError).userInfo[NSDebugDescriptionErrorKey] as? String ?? error.localizedDescription
    fail("couldn't read it: \(detail)")
}

func isIdentifier(_ key: String) -> Bool {
    key.range(of: "^[a-z][A-Za-z0-9]*$", options: .regularExpression) != nil
}

func render(_ object: [String: Any], path: String, indent: String) -> [String] {
    var lines: [String] = []
    for key in object.keys.sorted() {
        let value = object[key]!
        let keyPath = path.isEmpty ? key : "\(path).\(key)"
        if key.hasPrefix("_") {
            guard value is String else { fail("\(keyPath) starts with _ so it must be a comment string") }
            continue
        }
        guard isIdentifier(key) else { fail("\(keyPath): keys must be camelCase letters and digits") }
        if let nested = value as? [String: Any] {
            lines.append("\(indent)enum \(key.prefix(1).uppercased() + key.dropFirst()) {")
            lines += render(nested, path: keyPath, indent: indent + "    ")
            lines.append("\(indent)}")
        } else if let number = value as? NSNumber, CFGetTypeID(number) != CFBooleanGetTypeID() {
            lines.append("\(indent)static let \(key): CGFloat = \(number.doubleValue)")
        } else {
            fail("\(keyPath) must be a number or an object")
        }
    }
    return lines
}

let source = ([
    "// Generated by build.sh from Support/layout.json. Edit that file, not this one.",
    "import CoreGraphics",
    "",
    "enum Layout {",
] + render(root, path: "", indent: "    ") + ["}", ""]).joined(separator: "\n")

// Only write when something changed, so unchanged layouts don't trigger a recompile.
if (try? String(contentsOfFile: output, encoding: .utf8)) != source {
    do {
        try source.write(toFile: output, atomically: true, encoding: .utf8)
    } catch {
        fail("couldn't write \(output): \(error.localizedDescription)")
    }
}
